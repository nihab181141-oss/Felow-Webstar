/// <reference lib="webworker" />

import { clientsClaim } from 'workbox-core';
import { cleanupOutdatedCaches, precacheAndRoute } from 'workbox-precaching';
import { registerRoute } from 'workbox-routing';
import { CacheFirst, NetworkFirst, NetworkOnly, StaleWhileRevalidate } from 'workbox-strategies';
import { ExpirationPlugin } from 'workbox-expiration';
import { CacheableResponsePlugin } from 'workbox-cacheable-response';

declare const self: ServiceWorkerGlobalScope & {
  __WB_MANIFEST: Array<{ url: string; revision: string | null }>;
};

const PAGES_CACHE = 'felow-pages-v1';
const STATIC_MEDIA_CACHE = 'felow-static-media-v1';
const FONTS_CACHE = 'felow-fonts-v1';

// Take control cleanly after activation when triggered
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    void self.skipWaiting();
  }
});

self.skipWaiting();
clientsClaim();
cleanupOutdatedCaches();

// Precache static build shell generated by Vite + vite-plugin-pwa
precacheAndRoute(self.__WB_MANIFEST || []);

// 1. NEVER cache authentication, Firestore, Storage uploads, or backend API routes
const SENSITIVE_HOSTS = new Set([
  'firestore.googleapis.com',
  'identitytoolkit.googleapis.com',
  'securetoken.googleapis.com',
  'www.googleapis.com',
  'accounts.google.com',
  'firebasestorage.googleapis.com',
  'storage.googleapis.com'
]);

registerRoute(
  ({ url, request }) =>
    request.method !== 'GET' ||
    SENSITIVE_HOSTS.has(url.hostname) ||
    url.pathname.startsWith('/api/') ||
    url.pathname.startsWith('/__/auth'),
  new NetworkOnly()
);

// 2. Navigation requests: NetworkFirst so online stays fresh, cached pages work offline,
// and unvisited offline routes fall back gracefully to /offline.html
const navigationStrategy = new NetworkFirst({
  cacheName: PAGES_CACHE,
  networkTimeoutSeconds: 4,
  plugins: [
    new CacheableResponsePlugin({
      statuses: [200]
    }),
    new ExpirationPlugin({
      maxEntries: 30,
      maxAgeSeconds: 7 * 24 * 60 * 60
    })
  ]
});

registerRoute(
  ({ request, url }) =>
    request.mode === 'navigate' &&
    !url.pathname.startsWith('/api/') &&
    !url.pathname.startsWith('/__/auth'),
  async (options) => {
    try {
      const response = await navigationStrategy.handle(options);
      if (response) return response;
    } catch {
      // Network failed and this URL was not previously cached
    }
    const offlinePage = await caches.match('/offline.html');
    if (offlinePage) return offlinePage;
    const shell = await caches.match('/index.html');
    if (shell) return shell;
    return new Response('Offline', {
      status: 503,
      headers: { 'Content-Type': 'text/plain; charset=utf-8' }
    });
  }
);

// 3. Google Fonts stylesheets & font files (CacheFirst, 1 year)
registerRoute(
  ({ url }) =>
    url.origin === 'https://fonts.googleapis.com' ||
    url.origin === 'https://fonts.gstatic.com',
  new CacheFirst({
    cacheName: FONTS_CACHE,
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({
        maxEntries: 25,
        maxAgeSeconds: 365 * 24 * 60 * 60
      })
    ]
  })
);

// 4. Public static images, icons & brand SVG assets (StaleWhileRevalidate)
registerRoute(
  ({ request, url }) =>
    request.method === 'GET' &&
    url.origin === self.location.origin &&
    (request.destination === 'image' ||
      /\.(?:png|jpg|jpeg|svg|webp|ico)$/i.test(url.pathname)),
  new StaleWhileRevalidate({
    cacheName: STATIC_MEDIA_CACHE,
    plugins: [
      new CacheableResponsePlugin({ statuses: [200] }),
      new ExpirationPlugin({
        maxEntries: 80,
        maxAgeSeconds: 30 * 24 * 60 * 60
      })
    ]
  })
);

// 5. Real Web Push event handling (supports delivery even when app is closed)
interface PushNotificationPayload {
  title?: string;
  body?: string;
  message?: string;
  url?: string;
  tag?: string;
  icon?: string;
  badge?: string;
  actionView?: string;
  targetId?: string;
}

self.addEventListener('push', (event) => {
  let payload: PushNotificationPayload = {};
  if (event.data) {
    try {
      payload = event.data.json() as PushNotificationPayload;
    } catch {
      payload = { body: event.data.text() };
    }
  }

  const title = (payload.title || 'FeLoW WebStaR').slice(0, 128);
  const body = (
    payload.body ||
    payload.message ||
    'You have a new update on FeLoW WebStaR.'
  ).slice(0, 512);

  let targetUrl = '/';
  if (typeof payload.url === 'string' && payload.url.startsWith('/')) {
    targetUrl = payload.url;
  } else if (payload.actionView === 'tutor-detail' && payload.targetId) {
    targetUrl = `/tutors/${encodeURIComponent(payload.targetId)}`;
  } else if (payload.actionView === 'tuition-detail' && payload.targetId) {
    targetUrl = `/tuitions/${encodeURIComponent(payload.targetId)}`;
  } else if (payload.actionView === 'admin') {
    targetUrl = '/admin';
  } else if (payload.actionView === 'dashboard') {
    targetUrl = '/dashboard';
  }

  event.waitUntil(
    self.registration.showNotification(title, {
      body,
      icon: payload.icon || '/pwa-192x192.png',
      badge: payload.badge || '/pwa-192x192.png',
      tag: payload.tag || `felow-push-${Date.now()}`,
      data: {
        url: targetUrl,
        actionView: payload.actionView,
        targetId: payload.targetId
      }
    })
  );
});

// 6. Notification click opens/focuses the relevant page inside FeLoW WebStaR
self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const data = (event.notification.data || {}) as { url?: string };
  const relativePath =
    typeof data.url === 'string' && data.url.startsWith('/') ? data.url : '/';
  const destinationUrl = new URL(relativePath, self.location.origin).href;

  event.waitUntil(
    (async () => {
      const windowClients = await self.clients.matchAll({
        type: 'window',
        includeUncontrolled: true
      });

      for (const client of windowClients) {
        if (client.url.startsWith(self.location.origin) && 'focus' in client) {
          if ('navigate' in client && client.url !== destinationUrl) {
            await client.navigate(destinationUrl);
          }
          return client.focus();
        }
      }

      if (self.clients.openWindow) {
        return self.clients.openWindow(destinationUrl);
      }
      return undefined;
    })()
  );
});
